/// 인도네시아어 알파벳·발음 단위 — IPA · 조음 위치/입모양 · 한국어 화자 비교 (일본어앱 kana_phonetics 와 같은 역할).
///
/// IPA 는 표준 인도네시아어(bahasa baku) 음운 기준. 한글 독음은 docs/DIALOGUE.md §4 표와 같다(원어민 검수 전 초안).
/// 조음 위치 그림 번호 = assets/images/ipa/places_of_articulation.png 의 번호([placeNames]).
class IdSound {
  final String unit; // 화면에 보이는 글자 단위: a, b, ng, -k …
  final String name; // 알파벳 이름(읽는 법) 또는 묶음 설명
  final String rd; // 한글 보조 표기
  final String ipa;
  final String place; // 소리 나는 곳·입모양
  final List<int> nums; // 조음 위치 그림 번호
  final String korSim; // 비슷한 한국어 소리
  final String korDiff; // 한국어 화자가 틀리기 쉬운 점
  final List<(String, String, String)> examples; // (낱말, 한글 독음, 뜻)
  final String say; // 시트가 열리면 읽을 글(기기 음성)
  final VowelChartData? chart;
  const IdSound(this.unit, this.name, this.rd, this.ipa, this.place, this.nums, this.korSim, this.korDiff, this.examples, this.say, {this.chart});
  bool get vowel => chart != null;
}

class VowelPoint {
  final double x, y; // x 0 = 전설 … 1 = 후설, y 0 = 고 … 1 = 저
  final String ipa, label;
  const VowelPoint(this.x, this.y, this.ipa, this.label);
}

